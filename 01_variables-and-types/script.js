/* 
Naming Rules

1. Start with a letter, $ or _ (eg., myVariable, $myVariable, _myVariable, etc.)
2. Cannot contain spaces (e.g., my variable, my-variable, etc.)
3. Avoid reserved keywords (e.g., var, let, const, function, etc.)
*/


